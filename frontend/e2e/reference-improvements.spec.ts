async function fixture(request:APIRequestContext){
  const auth=await(await request.post('/api/login',{data:{username:'admin',password:'Farm@2026'}})).json()
  const headers={Authorization:'Bearer '+auth.token},suffix=randomUUID().slice(0,7)
  const save=async(kind:string,data:object)=>{const r=await request.post('/api/catalog/'+kind,{headers,data});expect(r.ok()).toBeTruthy();return r.json()}
  const g1=await save('groups',{name:'一组-'+suffix}),g2=await save('groups',{name:'二组-'+suffix})
  const basket=await save('baskets',{name:'大筐-'+suffix,weightKg:'1'}),gross=await save('grossWeights',{name:'毛重16公斤-'+suffix,weightKg:'16'})
  const worker=await save('workers',{name:'核对工人-'+suffix,code:'E2E-REF-'+suffix,groupId:g1.id})
  const b=await(await request.get('/api/bootstrap',{headers})).json()
  return {headers,g1,g2,basket,gross,worker,product:b.products.find((p:any)=>p.name==='小白菜'),date:b.today}
}
